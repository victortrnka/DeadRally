#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_entry_has_a_shape() {
        for entry in IMAGES {
            assert!(
                entry.width > 0 && entry.height > 0 && entry.frames > 0,
                "{}",
                entry.name
            );
            assert!(!entry.source.is_empty(), "{} needs a source", entry.name);
        }
    }

    #[test]
    fn no_entry_is_listed_twice() {
        // A duplicate would let two contradictory shapes for one image slip through.
        let mut keys: Vec<(&str, &str)> = IMAGES
            .iter()
            .map(|entry| (entry.archive, entry.name))
            .chain(NOT_IMAGES.iter().map(|entry| (entry.archive, entry.name)))
            .collect();
        let total = keys.len();
        keys.sort_unstable();
        keys.dedup();
        assert_eq!(keys.len(), total);
    }

    #[test]
    fn lookup_ignores_case() {
        assert_eq!(
            find("menu.bpa", "apogee.bpk").map(|entry| (entry.width, entry.height)),
            Some((640, 480))
        );
        assert!(find("MENU.BPA", "NOPE.BPK").is_none());
    }

    #[test]
    fn single_and_sliced_entries_cut_the_stream_into_frames() {
        // Two 2x1 frames in one stream: the second frame must start at byte 2.
        let entry = ImageEntry {
            archive: "T.BPA",
            name: "T.BPK",
            width: 2,
            height: 1,
            frames: 2,
            layout: Layout::Slices,
            palette: PaletteSource::Mask,
            transparent: false,
            source: "test",
        };
        let stored = |byte: u8| u16::from(byte.rotate_left(3));
        let codes = [257, stored(1), stored(2), stored(3), stored(4), 256];
        let mut stream = Vec::new();
        let (mut accumulator, mut bits) = (0u32, 0u32);
        for code in codes {
            accumulator |= u32::from(code) << bits;
            bits += 9;
            while bits >= 8 {
                stream.push((accumulator & 0xFF) as u8);
                accumulator >>= 8;
                bits -= 8;
            }
        }
        stream.push((accumulator & 0xFF) as u8);
        let frames = entry.decode(&stream).unwrap();
        assert_eq!(frames.len(), 2);
        assert_eq!(frames[1].pixels, [3, 4]);
        let wrong = ImageEntry { frames: 3, ..entry };
        assert_eq!(
            wrong.decode(&stream).unwrap_err(),
            CatalogError::Size {
                expected: 6,
                actual: 4
            }
        );
    }
}
