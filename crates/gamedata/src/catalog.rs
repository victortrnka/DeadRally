//! Every image in the original data, with the facts the data does not store: dimensions,
//! frame layout, palette and transparency (spec M1a §4.2). The facts come from reading
//! DreeRally (Windows decompilation) and dRally (DOS decompilation); `source` says where.

use std::fmt;

use crate::bpk::{self, BpkError};
use crate::image::{Image, PALETTE_BYTES, Palette, PaletteError};
use crate::track::{self, TrackError};

/// How an entry's decoded bytes hold its frames.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Layout {
    /// One stream, one image.
    Single,
    /// One stream cut into `frames` equal images.
    Slices,
    /// `frames` concatenated streams, one image each.
    Streams,
    /// A 768-byte palette, then one image (`FRAMES.BPK`).
    PaletteThenImage,
    /// A track image: RIX3 header, palette, pixels.
    Rix3Track,
}

/// Which palette the game uses when it draws the entry.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PaletteSource {
    Named {
        archive: &'static str,
        entry: &'static str,
    },
    /// The palette embedded in the current track's `-IMA` image (race graphics).
    Track,
    /// The palette inside the entry itself.
    Embedded,
    /// Not a picture: a mask where non-zero means "copy this pixel".
    Mask,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ImageEntry {
    pub archive: &'static str,
    pub name: &'static str,
    pub width: u32,
    pub height: u32,
    pub frames: u32,
    pub layout: Layout,
    pub palette: PaletteSource,
    /// Whether the game draws it with colour 0 transparent.
    pub transparent: bool,
    /// Where the facts come from (function and address in the original).
    pub source: &'static str,
}

/// A `.BPK` entry that is not a picture.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct NotImage {
    pub archive: &'static str,
    pub name: &'static str,
    pub reason: &'static str,
}

#[derive(Debug, PartialEq, Eq)]
pub enum CatalogError {
    Bpk(BpkError),
    Track(TrackError),
    Palette(PaletteError),
    /// The decoded data does not have the catalogued size.
    Size {
        expected: usize,
        actual: usize,
    },
    /// A multi-stream entry has a different number of streams.
    Streams {
        expected: u32,
        actual: usize,
    },
}

impl fmt::Display for CatalogError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            CatalogError::Bpk(error) => write!(f, "{error}"),
            CatalogError::Track(error) => write!(f, "{error}"),
            CatalogError::Palette(error) => write!(f, "{error}"),
            CatalogError::Size { expected, actual } => {
                write!(
                    f,
                    "decodes to {actual} bytes, the catalogue expects {expected}"
                )
            }
            CatalogError::Streams { expected, actual } => {
                write!(
                    f,
                    "holds {actual} streams, the catalogue expects {expected}"
                )
            }
        }
    }
}

impl std::error::Error for CatalogError {}

impl From<BpkError> for CatalogError {
    fn from(error: BpkError) -> CatalogError {
        CatalogError::Bpk(error)
    }
}

/// The catalogued entry `name` in `archive`; both match regardless of case.
#[must_use]
pub fn find(archive: &str, name: &str) -> Option<&'static ImageEntry> {
    IMAGES.iter().find(|entry| {
        entry.archive.eq_ignore_ascii_case(archive) && entry.name.eq_ignore_ascii_case(name)
    })
}

impl ImageEntry {
    fn frame_bytes(&self) -> usize {
        (self.width * self.height) as usize
    }

    /// Decodes the entry's bytes into its frames.
    ///
    /// # Errors
    ///
    /// [`CatalogError`] when the data is corrupt or does not match the catalogued shape.
    pub fn decode(&self, bytes: &[u8]) -> Result<Vec<Image>, CatalogError> {
        let frame = self.frame_bytes();
        let image = |pixels: &[u8]| Image::new(self.width, self.height, pixels.to_vec());
        match self.layout {
            Layout::Single | Layout::Slices => {
                let pixels = bpk::decode(bytes)?;
                let expected = frame * self.frames as usize;
                if pixels.len() != expected {
                    return Err(CatalogError::Size {
                        expected,
                        actual: pixels.len(),
                    });
                }
                Ok(pixels.chunks_exact(frame).map(image).collect())
            }
            Layout::Streams => {
                let streams = bpk::split_streams(bytes)?;
                if streams.len() != self.frames as usize {
                    return Err(CatalogError::Streams {
                        expected: self.frames,
                        actual: streams.len(),
                    });
                }
                streams
                    .iter()
                    .map(|stream| {
                        let pixels = bpk::decode(stream)?;
                        if pixels.len() == frame {
                            Ok(image(&pixels))
                        } else {
                            Err(CatalogError::Size {
                                expected: frame,
                                actual: pixels.len(),
                            })
                        }
                    })
                    .collect()
            }
            Layout::PaletteThenImage => {
                let decoded = bpk::decode(bytes)?;
                let expected = PALETTE_BYTES + frame;
                if decoded.len() != expected {
                    return Err(CatalogError::Size {
                        expected,
                        actual: decoded.len(),
                    });
                }
                Ok(vec![image(&decoded[PALETTE_BYTES..])])
            }
            Layout::Rix3Track => {
                let (image, _) = track::decode_rix3(bytes, self.width, self.height)
                    .map_err(CatalogError::Track)?;
                Ok(vec![image])
            }
        }
    }

    /// The palette stored inside the entry, for [`PaletteSource::Embedded`] entries.
    ///
    /// # Errors
    ///
    /// [`CatalogError`] when the data is corrupt.
    pub fn embedded_palette(&self, bytes: &[u8]) -> Result<Option<Palette>, CatalogError> {
        match self.layout {
            Layout::PaletteThenImage => {
                let decoded = bpk::decode_range(bytes, 0, PALETTE_BYTES)?;
                Palette::from_bytes(&decoded)
                    .map(Some)
                    .map_err(CatalogError::Palette)
            }
            Layout::Rix3Track => {
                let (_, palette) = track::decode_rix3(bytes, self.width, self.height)
                    .map_err(CatalogError::Track)?;
                Ok(Some(palette))
            }
            Layout::Single | Layout::Slices | Layout::Streams => Ok(None),
        }
    }
}

